"""Attempt an expanded exact model with all 640 non-dominated warehouse regions.

This is an exploratory step towards a global optimality certificate.  It fixes
the depot to 379 (as in the reference run) but removes the heuristic candidate
restriction: every warehouse that is not cost/distance-dominated is included.
The route pool is still generated by the savings heuristic, so the run is
*not* a proof over all feasible routes.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from scm.data import load_data
from scm.io import load_network, network_to_dict
from scm.milp import solve_milp
from scm.routes_pool import generate_pool

OUT = Path(__file__).resolve().parent
DEPOT = 379
TIME_LIMIT = 1800.0


def main() -> None:
    data = load_data("Projektdateien")
    raw = json.loads((OUT / "candidates_640.json").read_text())
    candidates = [int(w) for w in raw.get("candidates", raw["frontier"])]
    print(f"depot={DEPOT}, non-dominated warehouse candidates={len(candidates)}", flush=True)

    t0 = time.perf_counter()
    pool = generate_pool(data, candidates, pair_threshold_km=100.0, verbose=True)
    print(f"route pool: {len(pool)} routes ({time.perf_counter()-t0:.1f}s)", flush=True)

    initial = load_network("results/milp_200.json")
    t0 = time.perf_counter()
    result = solve_milp(
        data,
        pool,
        DEPOT,
        time_limit=TIME_LIMIT,
        verbose=True,
        initial=initial,
    )
    print(f"total solve runtime: {time.perf_counter()-t0:.1f}s", flush=True)

    payload = {
        "depot": result.network.depot,
        "candidates": candidates,
        "n_candidates": len(candidates),
        "network": network_to_dict(result.network),
        "breakdown": result.breakdown,
        "objective": result.objective,
        "mip_gap": result.mip_gap,
        "status": result.status,
        "runtime_s": result.runtime_s,
        "n_routes_pool": result.n_routes,
        "n_variables": result.n_variables,
        "n_constraints": result.n_constraints,
        "time_limit_s": TIME_LIMIT,
    }
    (OUT / "milp_640_integer_timeout.json").write_text(json.dumps(payload, indent=2))
    print(f"profit={result.breakdown['profit']/1e6:.6f} M EUR", flush=True)
    print(f"status={result.status}, gap={result.mip_gap:.4%}", flush=True)
    print(f"saved {OUT/'milp_640_integer_timeout.json'}", flush=True)


if __name__ == "__main__":
    main()
